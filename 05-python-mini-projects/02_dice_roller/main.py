print("Автор: Ира Улмаскулова")
print("Нажми Enter, чтобы бросить. Напиши 'exit' для выхода.\n")

# Бесконечный цикл, пока пользователь не захочет выйти
while True:
    choice = input("Бросить кубик? (Enter / exit): ").strip().lower()

    # Проверяем, хочет ли пользователь завершить программу
    if choice in ("exit", "q", "выход"):
        print("До встречи!")
        break

    # Генерируем случайное число от 1 до 6
    result = random.randint(1, 6)

    # Выводим соответствующую ASCII-картинку
    print(dice_faces[result])
    print(f"▶ Выпало: {result}\n")

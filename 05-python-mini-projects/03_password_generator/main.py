# Проект: Генератор паролей
# Описание: Создаёт случайный надёжный пароль заданной длины из букв, цифр и спецсимволов.

import random   # Для случайного выбора символов
import string   # Готовые наборы букв и цифр

print("=== Генератор надёжных паролей ===")
print("Автор: Ира Улмаскулова\n")

# Запрашиваем желаемую длину пароля
try:
    length = int(input("Введи длину пароля (рекомендуется 10–18): "))
except ValueError:
    # Если ввели не число — ставим значение по умолчанию
    print("Некорректный ввод. Установлена длина 14.")
    length = 14

# Защита от слишком коротких паролей
if length < 6:
    length = 6
    print("Минимальная длина — 6 символов. Ставлю 6.")

# Собираем все возможные символы:
# - буквы (верхний и нижний регистр)
# - цифры
# - специальные символы
chars = string.ascii_letters + string.digits + "!@#$%^&*_-+="

# Генерируем пароль: выбираем случайный символ length раз и склеиваем их
password = "".join(random.choice(chars) for _ in range(length))

# Выводим результат
print(f"\n🔐 Сгенерированный пароль: {password}")
print(f"Длина: {length} символов")

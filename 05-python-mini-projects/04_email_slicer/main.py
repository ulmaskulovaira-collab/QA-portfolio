# Проект: Email Slicer
# Описание: Разделяет email-адрес на имя пользователя и домен.

print("=== Email Slicer ===")
print("Автор: Ира Улмаскулова")
print("Разделяет адрес на имя пользователя и домен\n")

# Получаем email от пользователя и убираем лишние пробелы + приводим к нижнему регистру
email = input("Введи email-адрес: ").strip().lower()

# Проверяем, что в строке есть ровно один символ @
if "@" not in email or email.count("@") != 1:
    print("❌ Это не похоже на корректный email!")
else:
    # Разделяем строку по символу @ на две части
    username, domain = email.split("@", 1)

    # Дополнительная проверка: имя и домен не должны быть пустыми,
    # а в домене должна быть хотя бы одна точка
    if not username or not domain or "." not in domain:
        print("❌ Некорректный формат email!")
    else:
        # Красиво выводим результат
        print("\n────────────────────────")
        print(f"Имя пользователя : {username}")
        print(f"Домен            : {domain}")
        print("────────────────────────")

# Проект: Простой калькулятор
# Описание: Вычисляет математические выражения, введённые пользователем.

print("=== Калькулятор ===")
print("Автор: Ира Улмаскулова")
print("Поддерживаемые операции: +  -  *  /  %  **\n")

# Бесконечный цикл, пока пользователь не введёт команду выхода
while True:
    expr = input("Введи выражение (или 'exit' для выхода): ").strip()

    # Проверяем команду выхода
    if expr.lower() in ("exit", "q", "выход"):
        print("До встречи!")
        break

    try:
        # Простая проверка безопасности:
        # убираем ** и смотрим, остались ли только разрешённые символы
        cleaned = expr.replace("**", "")
        if not all(c in "0123456789+-*/%(). " for c in cleaned):
            print("Разрешены только числа и операции + - * / % **")
            continue

        # Вычисляем выражение.
        # __builtins__ = {} — запрещает доступ к встроенным функциям Python
        # (это базовая защита от вредоносного кода)
        result = eval(expr, {"__builtins__": {}})
        print(f"= {result}\n")

    except ZeroDivisionError:
        # Отдельно обрабатываем деление на ноль
        print("Ошибка: деление на ноль!\n")
    except Exception:
        # Любая другая ошибка (синтаксис, неправильные скобки и т.д.)
        print("Ошибка в выражении. Проверь синтаксис.\n")

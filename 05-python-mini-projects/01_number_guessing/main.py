# Проект: Игра «Угадай число»
# Описание: Компьютер загадывает число, игрок пытается его угадать за ограниченное количество попыток.

import random  # Модуль для генерации случайных чисел

print("=== Игра «Угадай число» ===")
print("Автор: Ира Улмаскулова")
print("Я загадала число от 1 до 25. У тебя 6 попыток.\n")

# Загадываем случайное число в диапазоне от 1 до 25
secret = random.randint(1, 25)

# Количество попыток, которые есть у игрока
attempts = 6

# Основной игровой цикл
while attempts > 0:
    try:
        # Запрашиваем у пользователя число
        guess = int(input(f"Осталось попыток: {attempts}. Твой вариант → "))
    except ValueError:
        # Если ввели не число — сообщаем об ошибке и продолжаем цикл
        print("Нужно ввести целое число!")
        continue

    # Проверяем, угадал ли игрок
    if guess == secret:
        print(f"\n🎉 Отлично! Это действительно {secret}")
        break  # Выходим из цикла, если угадали
    elif guess < secret:
        print("Загаданное число больше ↑")
    else:
        print("Загаданное число меньше ↓")

    # Уменьшаем количество оставшихся попыток
    attempts -= 1
else:
    # Этот блок выполнится, если цикл завершился без break (попытки закончились)
    print(f"\nПопытки закончились. Было загадано число: {secret}")
